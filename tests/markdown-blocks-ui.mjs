import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto('http://127.0.0.1:1420');
    const editor = page.getByRole('textbox', { name: '文档编辑器' });
    await editor.waitFor();
    assert.equal(await page.locator('.brand strong').innerText(), 'Inkode');
    assert.equal(await page.locator('.brand-mark svg').count(), 1);
    await page.getByRole('button', { name: '源码', exact: true }).click();
    const source = '# Blocks\n\n> first\n\n| Left | Middle | Right |\n| :--- | :---: | ---: |\n| **bold** | `code` | a \\| b |\n\n```mermaid\nflowchart LR\n    A[开始] --> B[完成]\n```\n\n```mermaid\nsequenceDiagram\n    A->>B: Hello\n```\n\nEnd';
    await editor.fill(source);
    await page.keyboard.press('ControlOrMeta+Home');
    await page.getByRole('button', { name: '即时预览', exact: true }).click();
    await page.getByRole('table', { name: 'Markdown 表格' }).waitFor();
    await page.locator('.md-mermaid-preview svg').first().waitFor({ timeout: 30000 });
    await page.waitForFunction(() => document.querySelectorAll('.md-mermaid-preview svg').length === 2);
    const table = page.getByRole('table', { name: 'Markdown 表格' });
    assert.equal(await table.locator('tbody td strong').innerText(), 'bold');
    assert.equal(await table.locator('tbody td code').innerText(), 'code');
    assert.equal(await table.locator('tbody td').last().innerText(), 'a | b');
    assert.equal(await table.locator('thead th').nth(1).evaluate((node) => getComputedStyle(node).textAlign), 'center');
    assert.equal(await table.locator('thead th').nth(2).evaluate((node) => getComputedStyle(node).textAlign), 'right');
    const quote = page.locator('.cm-line.md-quote').first();
    await quote.click();
    await page.keyboard.press('End');
    await page.keyboard.press('Enter');
    await page.keyboard.type('continued');
    assert.equal(await page.locator('.cm-line.md-quote').count(), 2, 'Enter continues quoted paragraph decoration');
    assert.match(await page.locator('.cm-line.md-quote').last().innerText(), /continued/);
    await page.locator('.md-table-preview').getByRole('button', { name: '编辑源码', exact: true }).click();
    assert.equal(await page.locator('.md-table-preview').count(), 0, 'table reveals source for editing');
    await page.keyboard.press('ControlOrMeta+Home');
    await table.waitFor();
    await page.locator('.md-mermaid-preview').first().getByRole('button', { name: '编辑源码', exact: true }).click();
    assert.equal(await page.locator('.md-mermaid-preview').count(), 1, 'diagram reveals source for editing');
    await page.keyboard.press('ControlOrMeta+Home');
    await page.waitForFunction(() => document.querySelectorAll('.md-mermaid-preview svg').length === 2);
    await page.getByRole('button', { name: '深色模式', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.md-mermaid-preview svg').length === 2);
    await page.getByRole('button', { name: '浅色模式', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.md-mermaid-preview svg').length === 2);
    await page.screenshot({ path: 'tests/markdown-blocks.png' });
    await page.getByRole('button', { name: '源码', exact: true }).click();
    const updated = await editor.innerText();
    assert.ok(updated.includes('> continued'), 'continued quote retains Markdown source');
    assert.ok(updated.includes('flowchart LR') && updated.includes('| **bold** |'), 'preview does not change source');
    await editor.fill('# Invalid\n\n```mermaid\nnot valid diagram code\n```\n\nEnd');
    await page.keyboard.press('ControlOrMeta+Home');
    await page.getByRole('button', { name: '即时预览', exact: true }).click();
    await page.locator('.md-diagram-error').waitFor({ timeout: 30000 });
    assert.match(await page.locator('.md-diagram-error').innerText(), /无法预览/);
    await page.getByRole('button', { name: '源码', exact: true }).click();
    await editor.fill(source);
    await page.keyboard.press('ControlOrMeta+Home');
    await page.getByRole('button', { name: '即时预览', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.md-mermaid-preview svg').length === 2);
    for (const width of [1280, 850, 560, 440]) {
        await page.setViewportSize({ width, height: 900 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow at ${width}`);
    }
    await page.getByRole('button', { name: '源码', exact: true }).click();
    await editor.fill(await readFile(new URL('../examples/mermaid.md', import.meta.url), 'utf8'));
    await page.keyboard.press('ControlOrMeta+Home');
    await page.getByRole('button', { name: '即时预览', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.md-mermaid-preview svg').length === 2);
    assert.equal(await page.locator('.md-diagram-error').count(), 0, 'shipped Mermaid examples render');
    assert.deepEqual(errors, []);
    console.log('Markdown blocks passed: quote Enter, table/inline/escaped-pipe/alignment, flowchart, sequence, edit source, theme, invalid syntax, source integrity, responsive, icon brand.');
} finally { await browser.close(); }
